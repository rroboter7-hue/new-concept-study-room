#!/usr/bin/env node
'use strict';
const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm'),crypto=require('node:crypto');
const sha=value=>crypto.createHash('sha256').update(value).digest('hex');

function documents(root=path.resolve(__dirname,'..')){
 const scope={};scope.window=scope;vm.createContext(scope);vm.runInContext(fs.readFileSync(path.join(root,'text-library.js'),'utf8'),scope,{filename:'text-library.js'});
 if(!Array.isArray(scope.TEXT_LIBRARY))throw Error('Missing text library catalogue.');
 return scope.TEXT_LIBRARY.map(item=>{
  if(!/^[a-z0-9-]+$/.test(item.id||''))throw Error('Invalid document identity.');
  if(Array.isArray(item.sections))return JSON.parse(JSON.stringify(item));
  const file=path.join(root,'text-data',item.id+'.json'),bytes=fs.readFileSync(file);
  if(sha(bytes)!==item.contentSha256)throw Error('Document checksum mismatch: '+item.id);
  const full=JSON.parse(bytes);if(full.id!==item.id||!Array.isArray(full.sections))throw Error('Invalid document data: '+item.id);return full;
 });
}

function build(root=path.resolve(__dirname,'..')){
 const full=documents(root),target=path.join(root,'text-data');fs.mkdirSync(target,{recursive:true});
 const descriptors=full.map(doc=>{
  // A single JSON line without a terminal newline keeps the checksum stable
  // when Git's Windows checkout policy converts text line endings.
  const bytes=Buffer.from(JSON.stringify(doc)),contentSha256=sha(bytes),first=doc.sections.findIndex(section=>(section.english||[]).length),{sections,...metadata}=doc;
  fs.writeFileSync(path.join(target,doc.id+'.json'),bytes);
  return {...metadata,sectionCount:sections.length,defaultSectionIndex:Math.max(0,first),dataUrl:'text-data/'+doc.id+'.json?sha256='+contentSha256,contentSha256};
 });
 const source='/* Source-note catalogue. Full original text loads per document on demand. Generated by dev/split-text-library.cjs. */\nwindow.TEXT_LIBRARY = '+JSON.stringify(descriptors)+';\n';
 fs.writeFileSync(path.join(root,'text-library.js'),source);
 return {documents:descriptors.length,sections:full.reduce((n,doc)=>n+doc.sections.length,0),catalogueBytes:Buffer.byteLength(source),dataBytes:full.reduce((n,doc)=>n+Buffer.byteLength(JSON.stringify(doc)),0)};
}
module.exports={documents,build};
if(require.main===module)console.log(JSON.stringify(build(),null,2));
